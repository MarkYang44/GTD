export function translate(key, language, values = {}) {
  const entry = copy[key];
  let text = entry?.[language === "zh" ? 1 : 0] ?? key;
  // Counts may arrive pre-formatted ("1,000"), so compare loosely against 1.
  if (typeof text === "object") text = values.count == 1 ? text.one : text.other;
  return text.replace(/\{(\w+)\}/g, (token, name) => values[name] ?? token);
}

// Backend progress and media fields use Chinese sentinels for unknown values.
export function localValue(value, language) {
  if (value === "计算中") return "…";
  if (value === "未知") return translate("unknown", language);
  if (value === "未知标题") return translate("untitled", language);
  return value;
}

