// Split a backend or transport error into a headline, a suggested fix and its code.
export function errorParts(error, language) {
  let payload = error;
  if (typeof error === "string") {
    try { payload = JSON.parse(error); } catch { return { message: error, suggestion: "", code: "" }; }
  }
  if (payload instanceof Error) return { message: payload.message, suggestion: "", code: "" };
  if (payload?.error && typeof payload.error === "object") payload = payload.error;
  const code = typeof payload?.error_code === "string" ? payload.error_code : "";
  const translated = language === "en" ? englishErrors[code] : null;
  let message = translated?.[0] || payload?.message || payload?.error || String(error);
  // Desktop validation messages are bilingual ("中文 / English"); keep the active language.
  const bilingual = !translated && typeof message === "string"
    && /^([^/]*[一-鿿][^/]*) \/ ([^一-鿿]+)$/.exec(message);
  if (bilingual) message = language === "zh" ? bilingual[1] : bilingual[2];
  return { message, suggestion: translated?.[1] || payload?.suggestion || "", code };
}

export function formatError(error, language) {
  const { message, suggestion, code } = errorParts(error, language);
  return [message, suggestion, code ? `[${code}]` : ""].filter(Boolean).join("\n");
}

