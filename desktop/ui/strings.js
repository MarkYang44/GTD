export function progressStage(item, language) {
  const step = item.postprocessing || item.progress;
  if (!step) return "";
  if (language === "zh") return step.stage_text || "";
  if (item.platform === "local") return translate("stageLocal", language);
  return step.stage || item.postprocessing ? translate(progressStages[step.stage] || "processing", language) : "";
}
